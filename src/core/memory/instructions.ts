// The instruction file: the Personal layer's Loaded tier, written where the
// harness loads it in full at every session start (the `instruction-file`
// Capability), because a hook's context has a cap the layer passes (ADR 0002,
// amendment 2026-11-12). `kalfa install` writes it first and records it in
// `install.yaml`; after that every `kalfa memory` command and every session
// start write it again, so the next session has the current records. A harness
// without the file gets the Personal layer in the session report.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { readInstallState } from '../install.ts';
import { memoryBudgets, type Settings } from '../settings.ts';
import { memoryHome, personalLayer, scanLayer } from './home.ts';
import { budgetOf, layerView, renderLayer } from './standing.ts';
import { readUsage } from './usage.ts';

const HEADER = [
	'# Standing memory (kalfa)',
	'',
	'Generated by kalfa from the Personal layer; do not edit it. Write a record only through `kalfa memory add|supersede|confirm`; what you find yourself is a Memory candidate first.',
].join('\n');

/** The text of the instruction file: the Personal layer's Loaded tier under its budget. */
export function personalInstructions(env: NodeJS.ProcessEnv, settings: Settings): string {
	const layer = personalLayer(memoryHome(env));
	const view = layerView(layer, scanLayer(layer).records, budgetOf(layer, memoryBudgets(settings)), readUsage(layer, env));
	const body = renderLayer(view);
	return `${HEADER}\n\n${body || 'Personal layer\nNo active records.'}\n`;
}

/** The instruction file kalfa installed for the harness, as an absolute path; `undefined` when there is none. */
export function installedInstructions(env: NodeJS.ProcessEnv, harness: string): string | undefined {
	const relativePath = readInstallState(env).harnesses[harness]?.instructions;
	return relativePath && env.HOME ? join(env.HOME, relativePath) : undefined;
}

/**
 * Writes the instruction file of each harness kalfa installed one for (or of
 * `harness` only) when its text changed. Returns the files that are current;
 * a file that cannot be written is left out, so the caller can fall back.
 */
export function refreshInstructions(env: NodeJS.ProcessEnv, settings: Settings, harness?: string): string[] {
	const harnesses = harness ? [harness] : Object.keys(readInstallState(env).harnesses);
	const paths = harnesses.map((name) => installedInstructions(env, name)).filter((path): path is string => path !== undefined);
	if (!paths.length) return [];
	const text = personalInstructions(env, settings);
	return paths.filter((path) => {
		try {
			if (existsSync(path) && readFileSync(path, 'utf8') === text) return true;
			mkdirSync(dirname(path), { recursive: true });
			writeFileSync(path, text);
			return true;
		} catch {
			return false;
		}
	});
}
