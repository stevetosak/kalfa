// Where Claude Code loads a Memory layer's Rule pack (ADR 0003). It reads
// every Markdown file under `.claude/rules/`, in the user's home and in the
// repository, at each session start; a file with `paths:` loads only when the
// agent reads or edits a file that matches. So the rules that load always go
// into one file per layer (each file costs a header in the context), and each
// path-scoped rule into its own file. Skills are found in `.claude/skills/`.
import { stringify } from 'yaml';
import { ruleItem } from '../../core/rules/files.ts';
import type { LayerRules, LoadedRule, RuleLayout } from '../adapter.ts';

const dir = (layer: LayerRules['layer']) => `.claude/rules/kalfa-${layer}`;

const title = (rules: LayerRules) => (rules.layer === 'personal' ? 'the Personal layer' : `the Project layer (${rules.label})`);

const change = (rules: LayerRules) => `kalfa rule add|change|remove --layer ${rules.layer}`;

function alwaysFile(rules: LayerRules): { path: string; text: string } {
	const header = [`# Rules of ${title(rules)} (kalfa)`, '', `Written by kalfa from the layer's Rule pack; do not edit this file. Change a rule with \`${change(rules)}\`.`];
	return { path: `${dir(rules.layer)}/always.md`, text: `${[...header, '', ...rules.always.map(ruleItem)].join('\n')}\n` };
}

function scopedFile(rules: LayerRules, rule: LoadedRule): { path: string; text: string } {
	const header = `---\n${stringify({ paths: rule.paths }).trimEnd()}\n---\n`;
	const note = `<!-- Written by kalfa from the Rule pack of ${title(rules)}. Change it with \`kalfa rule change ${rule.id} --layer ${rules.layer}\`. -->`;
	return { path: `${dir(rules.layer)}/paths/${rule.id}.md`, text: `${header}${note}\n\n${rule.text}\n` };
}

export const claudeRules: RuleLayout = {
	dir,
	files: (rules) => [...(rules.always.length ? [alwaysFile(rules)] : []), ...rules.scoped.map((rule) => scopedFile(rules, rule))],
	skillDir: (name) => `.claude/skills/${name}`,
};
